// The command-line tool: `rpn-typesetter paper.rtex` writes `paper.tex`.
// Invalid RPN is reported, and each invalid block becomes a LaTeX error
// followed by a bold ??, as in the LuaLaTeX package: when LaTeX reaches it,
// it stops and waits, then typesets ?? in its place. The tool exits 1, so a
// script notices, except under --latexmk, so latexmk goes on to run LaTeX.
//
// The files the document \input's or \include's are converted too, when
// they're .rtex files: `\input{chapter}` converts chapter.rtex to
// chapter.tex, which LaTeX then reads.
//
// `rpn-typesetter --latexmk FILE` is for latexmk's pdfLaTeX command: it
// converts FILE if it's a .rtex file and does nothing otherwise, so one
// global ~/.latexmkrc line serves .rtex and ordinary .tex projects alike.

import { existsSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { basename, dirname, join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import type { Diagnostic } from "./lexer.js";
import { readMeasurements, type Measurement } from "./breaking.js";
import { convert, locate } from "./scanner.js";

/** The start of the guard line at the top of every generated file. */
export const guardPrefix = "% Generated by rpn-typesetter";

function guardLine(source: string): string {
  return `${guardPrefix} from ${basename(source)}. Do not edit; edit ${basename(source)} instead.\n`;
}

/** `paper.rtex:12:8: error: …`, a format editors can jump to. */
function format(file: string, document: string, severity: string, d: Diagnostic): string {
  const { line, column } = locate(document, d.start);
  return `${file}:${line}:${column}: ${severity}: ${d.message}`;
}

/**
 * Escapes text for a LaTeX message (\typeout, \PackageError), so `\`, `{`
 * and the like are printed, not run. A brace or `#` is made from a control
 * symbol: `\string\{` is `\{`, and \@gobble drops the backslash. A
 * backslash or `%` is LaTeX's \@backslashchar or \@percentchar. (\csname
 * reaches these @ commands without the document making @ a letter.) A
 * letter or space right after such a command is separated from it, since
 * TeX would join a letter to the command's name and drop a space.
 */
export function latexMessage(text: string): string {
  const named: Readonly<Record<string, string>> = { "\\": "@backslashchar", "%": "@percentchar" };
  let out = "";
  let afterCommand = false;
  for (const c of text) {
    const name = named[c];
    if (name !== undefined) {
      out += `\\csname ${name}\\endcsname`;
      afterCommand = true;
    } else if ("{}#".includes(c)) {
      out += `\\csname @gobble\\expandafter\\endcsname\\string\\${c}`;
      afterCommand = false;
    } else if ("$&^_~".includes(c)) {
      out += `\\string${c}`;
      afterCommand = false;
    } else if (afterCommand && c === " ") {
      out += "\\space";
    } else {
      out += afterCommand && /[A-Za-z]/.test(c) ? ` ${c}` : c;
      afterCommand = false;
    }
  }
  return out;
}

/**
 * The LaTeX an invalid block becomes: its errors written to LaTeX's log as
 * `paper.rtex:12:8: error: …`, a LaTeX error (raised once, though align reads
 * its contents twice), then a bold ??, like a missing reference.
 */
function invalidBlock(file: string, document: string, errors: readonly Diagnostic[], n: number): string {
  const flag = `\\csname rpn-typesetter error ${n}\\endcsname`;
  const lines = errors.map((e) => `\\typeout{${latexMessage(format(file, document, "error", e))}}`).join("");
  const more = errors.length - 1;
  const message = errors[0]!.message + (more > 0 ? ` (and ${more} more error${more === 1 ? "" : "s"})` : "");
  const help = "This RPN is invalid, so ?? is typeset in its place. Fix it and run LaTeX again.";
  return (
    `\\ifcsname rpn-typesetter error ${n}\\endcsname\\else\\expandafter\\gdef${flag}{}` +
    `${lines}\\PackageError{rpn-typesetter}{${latexMessage(message)}}{${help}}\\fi\\mbox{\\normalfont\\bfseries ??}`
  );
}

/** The installed version, from package.json (next to dist/ when installed, next to src/ in a clone). */
export function version(): string {
  const pkg: unknown = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8"));
  return typeof pkg === "object" && pkg !== null && "version" in pkg ? String(pkg.version) : "unknown";
}

/** Runs the tool. Returns the exit code. */
export function main(args: readonly string[], log: (line: string) => void = console.error): number {
  if (args.length === 1 && args[0] === "--version") {
    console.log(version());
    return 0;
  }
  const fromLatexmk = args[0] === "--latexmk";
  const [source, ...rest] = fromLatexmk ? args.slice(1) : args;
  if (fromLatexmk && source !== undefined && rest.length === 0 && !source.endsWith(".rtex")) return 0;
  if (source === undefined || rest.length > 0 || !source.endsWith(".rtex")) {
    log("usage: rpn-typesetter [--latexmk] <file.rtex>   or   rpn-typesetter --version");
    return 2;
  }
  if (!existsSync(source)) {
    log(`rpn-typesetter: ${source} does not exist`);
    return 2;
  }

  // LaTeX looks for an \input file from the folder it runs in, which latexmk
  // makes the document's own.
  const folder = dirname(source);
  const converted = new Set<string>();
  let blocks = 0; // numbers invalid blocks across every file, as LaTeX reads them as one document
  let code = 0;

  // Widths LaTeX measured on its last run, so long equations can be broken
  // (see breaking.ts). They're shared by every file, as are the counts of
  // repeated equations that measurement IDs include, so an ID names one
  // equation in the whole document.
  const measurements = new Map<string, Measurement>();
  const occurrences = new Map<string, number>();
  let standalone = false; // whether the document has \documentclass, so its parts can be measured too

  const convertFile = (file: string, part: boolean): void => {
    converted.add(resolve(file));
    const target = file.replace(/\.rtex$/, ".tex");
    if (existsSync(target) && !readFileSync(target, "utf8").startsWith(guardPrefix)) {
      log(`rpn-typesetter: ${target} wasn't generated by rpn-typesetter, so it won't be overwritten`);
      code = 2;
      return;
    }

    // The document's .aux holds the widths for it and the files it \inputs;
    // an \include'd file writes its own .aux next to it.
    const aux = file.replace(/\.rtex$/, ".aux");
    if (existsSync(aux)) for (const [id, m] of readMeasurements(readFileSync(aux, "utf8"))) measurements.set(id, m);

    const document = readFileSync(file, "utf8");
    const result = convert(document, {
      measurements,
      occurrences,
      ...(part ? { measure: standalone } : {}),
      invalid: (blockErrors) => invalidBlock(file, document, blockErrors, ++blocks),
    });
    const { output, errors, warnings, inputs } = result;
    if (!part) standalone = result.standalone;
    for (const w of warnings) log(format(file, document, "warning", w));
    for (const e of errors) log(format(file, document, "error", e));
    writeFileSync(target, guardLine(file) + output);
    if (errors.length > 0 && !fromLatexmk) code = Math.max(code, 1);

    for (const name of inputs) {
      const included = join(folder, `${name.replace(/\.tex$/, "")}.rtex`);
      if (existsSync(included) && !converted.has(resolve(included))) convertFile(included, true);
    }
  };

  convertFile(source, false);
  return code;
}

/**
 * Whether the script started as `script` (process.argv[1]) is the module at
 * `moduleUrl`. `npm link` and global installs start it through a symlink, so
 * compare real paths, not the paths as given.
 */
export function isMainModule(moduleUrl: string, script: string | undefined): boolean {
  if (script === undefined) return false;
  try {
    return pathToFileURL(realpathSync(script)).href === moduleUrl;
  } catch {
    return false;
  }
}

if (isMainModule(import.meta.url, process.argv[1])) {
  process.exitCode = main(process.argv.slice(2));
}
