#!/usr/bin/env node
// The command-line tool: `rpn-typesetter paper.rtex` writes `paper.tex`.
// Invalid RPN stops it with exit code 1 and nothing written, so a
// `latexmk` command that runs it first never reaches LaTeX.
//
// `rpn-typesetter --latexmk FILE` is for latexmk's pdfLaTeX command: it
// converts FILE if it's a .rtex file and does nothing otherwise, so one
// global ~/.latexmkrc line serves .rtex and ordinary .tex projects alike.

import { existsSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { basename } from "node:path";
import { pathToFileURL } from "node:url";
import type { Diagnostic } from "./lexer.js";
import { readMeasurements } from "./breaking.js";
import { convert, locate } from "./scanner.js";

/** The start of the guard line at the top of every generated file. */
export const guardPrefix = "% Generated by rpn-typesetter";

function guardLine(source: string): string {
  return `${guardPrefix} from ${basename(source)}. Do not edit; edit ${basename(source)} instead.\n`;
}

/** `paper.rtex:12:8: error: …`, a format editors can jump to. */
function format(file: string, document: string, severity: string, d: Diagnostic): string {
  const { line, column } = locate(document, d.start);
  return `${file}:${line}:${column}: ${severity}: ${d.message}`;
}

/** The installed version, from package.json (next to dist/ when installed, next to src/ in a clone). */
export function version(): string {
  const pkg: unknown = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8"));
  return typeof pkg === "object" && pkg !== null && "version" in pkg ? String(pkg.version) : "unknown";
}

/** Runs the tool. Returns the exit code. */
export function main(args: readonly string[], log: (line: string) => void = console.error): number {
  if (args.length === 1 && args[0] === "--version") {
    console.log(version());
    return 0;
  }
  const fromLatexmk = args[0] === "--latexmk";
  const [source, ...rest] = fromLatexmk ? args.slice(1) : args;
  if (fromLatexmk && source !== undefined && rest.length === 0 && !source.endsWith(".rtex")) return 0;
  if (source === undefined || rest.length > 0 || !source.endsWith(".rtex")) {
    log("usage: rpn-typesetter [--latexmk] <file.rtex>   or   rpn-typesetter --version");
    return 2;
  }
  if (!existsSync(source)) {
    log(`rpn-typesetter: ${source} does not exist`);
    return 2;
  }

  const target = source.replace(/\.rtex$/, ".tex");
  if (existsSync(target) && !readFileSync(target, "utf8").startsWith(guardPrefix)) {
    log(`rpn-typesetter: ${target} wasn't generated by rpn-typesetter, so it won't be overwritten`);
    return 2;
  }

  // Widths LaTeX measured on its last run, so long equations can be broken.
  const aux = source.replace(/\.rtex$/, ".aux");
  const measurements = existsSync(aux) ? readMeasurements(readFileSync(aux, "utf8")) : new Map();

  const document = readFileSync(source, "utf8");
  const { output, errors, warnings } = convert(document, { measurements });
  for (const w of warnings) log(format(source, document, "warning", w));
  for (const e of errors) log(format(source, document, "error", e));
  if (errors.length > 0) return 1;

  writeFileSync(target, guardLine(source) + output);
  return 0;
}

/**
 * Whether the script started as `script` (process.argv[1]) is the module at
 * `moduleUrl`. `npm link` and global installs start it through a symlink, so
 * compare real paths, not the paths as given.
 */
export function isMainModule(moduleUrl: string, script: string | undefined): boolean {
  if (script === undefined) return false;
  try {
    return pathToFileURL(realpathSync(script)).href === moduleUrl;
  } catch {
    return false;
  }
}

if (isMainModule(import.meta.url, process.argv[1])) {
  process.exitCode = main(process.argv.slice(2));
}
