import { existsSync, mkdirSync, mkdtempSync, readFileSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { beforeEach, describe, expect, it } from "vitest";
import { guardPrefix, isMainModule, latexMessage, main, version } from "../src/cli.js";

describe("command-line tool", () => {
  let dir: string;
  let logged: string[];
  const run = (...args: string[]) => main(args, (line) => logged.push(line));

  beforeEach(() => {
    dir = mkdtempSync(join(tmpdir(), "rpn-"));
    logged = [];
  });

  it("writes paper.tex with a guard line on top", () => {
    const source = join(dir, "paper.rtex");
    writeFileSync(source, "$@ a b +$\n");
    expect(run(source)).toBe(0);
    expect(readFileSync(join(dir, "paper.tex"), "utf8")).toBe(
      `${guardPrefix} from paper.rtex. Do not edit; edit paper.rtex instead.\n$ a + b $\n`,
    );
  });

  it("overwrites a file it generated before", () => {
    const source = join(dir, "paper.rtex");
    writeFileSync(source, "$@ a$\n");
    expect(run(source)).toBe(0);
    writeFileSync(source, "$@ b$\n");
    expect(run(source)).toBe(0);
    expect(readFileSync(join(dir, "paper.tex"), "utf8")).toContain("$ b $");
  });

  it("refuses to overwrite a hand-written paper.tex", () => {
    const source = join(dir, "paper.rtex");
    writeFileSync(source, "$@ a$\n");
    writeFileSync(join(dir, "paper.tex"), "my own work\n");
    expect(run(source)).toBe(2);
    expect(readFileSync(join(dir, "paper.tex"), "utf8")).toBe("my own work\n");
    expect(logged[0]).toContain("wasn't generated by rpn-typesetter");
  });

  it("reports errors as file:line:column, writes ?? and a LaTeX error, and exits 1", () => {
    const source = join(dir, "paper.rtex");
    writeFileSync(source, "Intro.\n$@ a +$ and $@ b c +$\n");
    expect(run(source)).toBe(1);
    expect(logged).toEqual([`${source}:2:6: error: \`+\` needs 2 values, but only 1 is available`]);
    const output = readFileSync(join(dir, "paper.tex"), "utf8").split("\n")[2]!;
    expect(output).toMatch(/^\$ \\ifcsname rpn-typesetter error 1\\endcsname.*\\PackageError\{rpn-typesetter\}.*\\mbox\{\\normalfont\\bfseries \?\?\} \$ and \$ b \+ c \$$/);
  });

  it("exits 0 for invalid RPN under --latexmk, so latexmk runs LaTeX, which reports it", () => {
    const source = join(dir, "paper.rtex");
    writeFileSync(source, "$@ a +$\n");
    expect(run("--latexmk", source)).toBe(0);
    expect(logged).toHaveLength(1);
    expect(readFileSync(join(dir, "paper.tex"), "utf8")).toContain("\\PackageError");
  });

  it("escapes messages for LaTeX", () => {
    const brace = "\\csname @gobble\\expandafter\\endcsname\\string\\{";
    expect(latexMessage("`\\overset` needs {")).toBe(`\`\\csname @backslashchar\\endcsname overset\` needs ${brace}`);
    expect(latexMessage("% x _")).toBe("\\csname @percentchar\\endcsname\\space x \\string_");
  });

  it("prints warnings but still writes the file", () => {
    const source = join(dir, "paper.rtex");
    writeFileSync(source, "$@ 2 x$\n");
    expect(run(source)).toBe(0);
    expect(logged[0]).toMatch(/paper\.rtex:1:4: warning: 2 values were left on the stack/);
  });

  it("converts the .rtex files the document \\inputs or \\includes, and theirs", () => {
    const source = join(dir, "paper.rtex");
    writeFileSync(source, "\\input{one}\n\\include{parts/two.tex}\n% \\input{commented}\n\\input{plain}\n");
    writeFileSync(join(dir, "one.rtex"), "$@ a b +$ \\input{three}\n");
    mkdirSync(join(dir, "parts"));
    writeFileSync(join(dir, "parts", "two.rtex"), "$@ c d +$\n");
    writeFileSync(join(dir, "three.rtex"), "$@ e f +$ \\input{paper}\n"); // a cycle back to the start
    writeFileSync(join(dir, "commented.rtex"), "$@ g$\n");
    writeFileSync(join(dir, "plain.tex"), "untouched\n");
    expect(run(source)).toBe(0);
    expect(readFileSync(join(dir, "one.tex"), "utf8")).toContain("$ a + b $");
    expect(readFileSync(join(dir, "parts", "two.tex"), "utf8")).toContain("$ c + d $");
    expect(readFileSync(join(dir, "three.tex"), "utf8")).toContain("$ e + f $");
    expect(existsSync(join(dir, "commented.tex"))).toBe(false);
    expect(readFileSync(join(dir, "plain.tex"), "utf8")).toBe("untouched\n");
  });

  it("reports errors in an included file under its own name, numbering blocks across files", () => {
    const source = join(dir, "paper.rtex");
    writeFileSync(source, "$@ a +$ \\input{chapter}\n");
    writeFileSync(join(dir, "chapter.rtex"), "Text.\n$@ b +$\n");
    expect(run(source)).toBe(1);
    expect(logged).toEqual([
      `${source}:1:6: error: \`+\` needs 2 values, but only 1 is available`,
      `${join(dir, "chapter.rtex")}:2:6: error: \`+\` needs 2 values, but only 1 is available`,
    ]);
    expect(readFileSync(join(dir, "paper.tex"), "utf8")).toContain("rpn-typesetter error 1\\endcsname");
    expect(readFileSync(join(dir, "chapter.tex"), "utf8")).toContain("rpn-typesetter error 2\\endcsname");
  });

  it("won't overwrite a hand-written .tex for an included file", () => {
    const source = join(dir, "paper.rtex");
    writeFileSync(source, "\\input{chapter}\n");
    writeFileSync(join(dir, "chapter.rtex"), "$@ a$\n");
    writeFileSync(join(dir, "chapter.tex"), "my own work\n");
    expect(run(source)).toBe(2);
    expect(readFileSync(join(dir, "chapter.tex"), "utf8")).toBe("my own work\n");
  });

  it("knows its version", () => {
    expect(version()).toMatch(/^\d+\.\d+\.\d+$/);
  });

  it("explains its usage", () => {
    expect(run()).toBe(2);
    expect(run("paper.tex")).toBe(2);
    expect(logged[0]).toBe("usage: rpn-typesetter [--latexmk] <file.rtex>   or   rpn-typesetter --version");
  });

  it("converts a .rtex file with --latexmk, and leaves any other file alone", () => {
    const source = join(dir, "paper.rtex");
    writeFileSync(source, "$@ a b +$\n");
    expect(run("--latexmk", source)).toBe(0);
    expect(readFileSync(join(dir, "paper.tex"), "utf8")).toContain("$ a + b $");

    const plain = join(dir, "other.tex");
    writeFileSync(plain, "untouched\n");
    expect(run("--latexmk", plain)).toBe(0);
    expect(readFileSync(plain, "utf8")).toBe("untouched\n");
    expect(logged).toEqual([]);
  });

  it("recognises itself when started through a symlink, as npm link installs it", () => {
    const script = join(dir, "cli.js");
    writeFileSync(script, "");
    symlinkSync(script, join(dir, "rpn-typesetter"));
    const url = pathToFileURL(script).href;
    expect(isMainModule(url, script)).toBe(true);
    expect(isMainModule(url, join(dir, "rpn-typesetter"))).toBe(true);
    expect(isMainModule(url, join(dir, "something-else.js"))).toBe(false);
    expect(isMainModule(url, undefined)).toBe(false);
  });
});
